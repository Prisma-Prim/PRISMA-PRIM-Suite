export function useClientDirectoryCopy() {
  const message = useMessages(clientDirectoryMessages);
  const { formatNumber } = useInterfaceLocale();
  return {
    eyebrow: message('eyebrow'),
    title: message('title'),
    newClient: message('newClient'),
    directoryCompany: (company: string) =>
      formatMessage(message('directoryCompany'), { company }),
    description: message('description'),
    directoryClient: message('directoryClient'),
    directoryRelationship: message('directoryRelationship'),
    directoryActions: message('directoryActions'),
    resultsShown: (count: number) =>
      formatMessage(message(count === 1 ? 'oneResultShown' : 'resultsShown'), {
        count: formatNumber(count),
      }),
    workspaceSearchHint: message('workspaceSearchHint'),
    companySearchHint: message('companySearchHint'),
    searchLimitHint: message('searchLimitHint'),
    showCompanyClients: message('showCompanyClients'),
    addingToCompany: (company: string) =>
      formatMessage(message('addingToCompany'), { company }),
    loading: message('loading'),
    missingCompany: message('missingCompany'),
    permissionDenied: message('permissionDenied'),
    retryableError: message('retryableError'),
    searchLabel: message('searchLabel'),
    search: message('search'),
    searching: message('searching'),
    searchRequired: message('searchRequired'),
    noSearchResults: message('noSearchResults'),
    notYetLinkedToCompany: (company: string) =>
      formatMessage(message('notYetLinkedToCompany'), { company }),
    notAvailableInCompany: message('notAvailableInCompany'),
    searchResultsTitle: message('searchResultsTitle'),
    clientId: (id: string) => formatMessage(message('clientId'), { id }),
    openDossier: message('openDossier'),
    addToCompany: (company: string) =>
      formatMessage(message('addToCompany'), { company }),
    availableInCompany: (company: string) =>
      formatMessage(message('availableInCompany'), { company }),
    empty: (company: string) => formatMessage(message('empty'), { company }),
  };
}
