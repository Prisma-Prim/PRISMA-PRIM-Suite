export function useMultiCompanySummaryCopy() {
  const message = useMessages(multiCompanySummaryMessages);
  return {
    message,
    format: (
      key: (typeof keys)[number],
      values: Readonly<Record<string, string | number>>,
    ) => formatMessage(message(key), values),
  };
}
