export function useAnalysisIssue() {
  const { locale } = useInterfaceLocale();
  return (code: string) => {
    const group =
      issueGroups.get(code) ??
      (code.includes('limit') ? 'limit' : 'unsupported');
    return issueCopy[locale][group];
  };
}
