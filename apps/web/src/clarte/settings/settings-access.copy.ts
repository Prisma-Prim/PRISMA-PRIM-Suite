export type RightsGroup =
  | 'company'
  | 'commercial'
  | 'delivery'
  | 'documents'
  | 'certification'
  | 'finance'
  | 'improvement';

export function useSettingsAccessCopy() {
  const message = useMessages(settingsAccessMessages);
  const groups = {
    company: message('groupCompany'),
    commercial: message('groupCommercial'),
    delivery: message('groupDelivery'),
    documents: message('groupDocuments'),
    certification: message('groupCertification'),
    finance: message('groupFinance'),
    improvement: message('groupImprovement'),
  } satisfies Record<RightsGroup, string>;
  const invitationStatuses = {
    uncertain: message('invitationUncertain'),
    pending: message('invitationPending'),
    accepted: message('invitationAccepted'),
    revoked: message('invitationRevoked'),
    expired: message('invitationExpired'),
    rejected: message('invitationRejected'),
  } satisfies Record<InvitationStatus, string>;
  const revocationStatuses = {
    pending: message('revocationPending'),
    running: message('revocationRunning'),
    retry_required: message('revocationRetryRequired'),
    complete: message('revocationComplete'),
  } satisfies Record<SessionRevocationStatus, string>;
  return {
    membersTitle: message('membersTitle'),
    rightsTab: message('rightsTab'),
    personColumn: message('personColumn'),
    companiesColumn: message('companiesColumn'),
    noRights: message('noRights'),
    rightsHint: message('rightsHint'),
    accessForbidden: message('accessForbidden'),
    rightsGroup: (group: RightsGroup) => groups[group],
    bundleAction: message('bundleAction'),
    inviteTitle: message('inviteTitle'),
    sentTitle: message('sentTitle'),
    expiryHint: message('expiryHint'),
    invitationStatus: (status: InvitationStatus) => invitationStatuses[status],
    invitationConsumed: message('invitationConsumed'),
    revocationStatus: (status: SessionRevocationStatus) =>
      revocationStatuses[status],
  };
}
