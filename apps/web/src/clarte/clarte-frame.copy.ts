const entryKeys = {
  today: 'entryToday',
  deals: 'entryDeals',
  clients: 'entryClients',
  missions: 'entryMissions',
  tasks: 'entryTasks',
  documents: 'entryDocuments',
  finance: 'entryFinance',
  improvement: 'entryImprovement',
  settings: 'entrySettings',
} as const satisfies Record<ClarteEntryId, (typeof keys)[number]>;

export function useClarteFrameCopy() {
  const message = useMessages(clarteFrameMessages);
  return {
    primaryNavigation: message('primaryNavigation'),
    phoneNavigation: message('phoneNavigation'),
    skipToContent: message('skipToContent'),
    brandHome: message('brandHome'),
    brandTagline: message('brandTagline'),
    entry: (id: ClarteEntryId) => message(entryKeys[id]),
    tabsLabel: (entry: string) =>
      formatMessage(message('tabsLabel'), { entry }),
    jumpOpen: message('jumpOpen'),
    jumpPlaceholder: message('jumpPlaceholder'),
    jumpInputLabel: message('jumpInputLabel'),
    jumpEmpty: message('jumpEmpty'),
    jumpHint: message('jumpHint'),
    noCompany: message('noCompany'),
    recentChanges: message('recentChanges'),
    userMenu: message('userMenu'),
    leaveClarte: message('leaveClarte'),
    signOut: message('signOut'),
    more: message('more'),
    moreTitle: message('moreTitle'),
    greeting: (name: string) => formatMessage(message('greeting'), { name }),
  };
}
