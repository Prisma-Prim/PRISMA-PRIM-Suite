/** Plain texts by key, and the three texts that take values. */
export function useClarteMissionsCopy() {
  const message = useMessages(clarteMissionsMessages);
  return {
    text: message,
    planCopied: (title: string, version: number) =>
      formatMessage(message('planCopied'), { title, version }),
    openTaskOf: (activity: string) =>
      formatMessage(message('openTaskOf'), { activity }),
    registeredOn: (date: string) =>
      formatMessage(message('registeredOn'), { date }),
  };
}
