type Key = (typeof keys)[number];

export function useClarteTodayCopy() {
  const message = useMessages(clarteTodayMessages);
  const format =
    (key: Key) =>
    (values: Readonly<Record<string, string | number>>): string =>
      formatMessage(message(key), values);
  return {
    message,
    weekRange: format('weekRange'),
    weekShown: format('weekShown'),
    companyCounted: format('companyCounted'),
    captured: format('captured'),
    affaireChoice: format('affaireChoice'),
    workPosition: format('workPosition'),
    workOpenNamed: format('workOpenNamed'),
    whyDecision: format('whyDecision'),
    whyUpcoming: format('whyUpcoming'),
    decisionContext: format('decisionContext'),
    taskContext: format('taskContext'),
    reviewPage: format('reviewPage'),
  };
}
