export function useMyTasksCopy() {
  const message = useMessages(myTasksMessages);
  return {
    title: message('title'),
    note: message('note'),
    listLabel: message('listLabel'),
    refresh: message('refresh'),
    loading: message('loading'),
    empty: message('empty'),
    denied: message('denied'),
    error: message('error'),
    retry: message('retry'),
    project: message('project'),
    client: message('client'),
    open: message('open'),
    openTask: (values: { task: string; project: string; client: string }) =>
      formatMessage(message('openTask'), values),
    dueDate: message('dueDate'),
    noDate: message('noDate'),
    priority: message('priority'),
    states: {
      todo: message('todo'),
      in_progress: message('inProgress'),
      blocked: message('blocked'),
    } satisfies Record<OpenTaskState, string>,
    priorities: {
      normal: message('normal'),
      important: message('important'),
      critical: message('critical'),
    } satisfies Record<TaskPriority, string>,
  };
}
